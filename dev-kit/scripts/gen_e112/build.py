import os
UNITS=[u for u in ['u11','u12','u13','u14','u15','u1','u2','u3','u4','u5'] if os.path.exists(f'/home/claude/gen/e112/{u}.py')]
units={};lessons={};acts={};E={};PAGES={}
def add(lid,ex,title,given,ask,steps,answer):
    bad=[s for s in steps if s.get('bad')];assert len(bad)==1,title
    if len(steps)<2: steps.insert(0,{'t':'المعطى: '+given})
    b=bad[0];n=len(b['reasons']);assert 3<=n<=4
    k=(sum(len(v) for v in E.values())*3+1)%n;rs=b['reasons'];good=rs[b['rc']];rs=rs[k:]+rs[:k];b['reasons']=rs;b['rc']=rs.index(good)
    E.setdefault(lid,[]).append(dict(ex=ex,title=title,given=given,ask=ask,steps=steps,answer=answer))
T=lambda t:{'t':t}
def Bd(t,why,fix,reasons,rc=0):return {'t':t,'bad':True,'why':why,'fix':fix,'reasons':reasons,'rc':rc}
for u in UNITS:
    m=importlib.import_module(u);units.update(m.UNIT);lessons.update(m.LESS);acts.update(m.ACTS);PAGES.update(m.PAGES)
    (m if hasattr(m,'build') else importlib.import_module('errs'+u[1:])).build(add,T,Bd)
